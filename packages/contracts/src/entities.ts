import { z } from 'zod';

/** Server-generated ids (UUIDv7/ULID/...). Kept loose on purpose. */
export const Id = z.string().min(1).max(64);

export const WorkspaceRole = z.enum(['owner', 'admin', 'member']);
export type WorkspaceRole = z.infer<typeof WorkspaceRole>;

export const User = z.object({
  id: Id,
  email: z.email(),
  displayName: z.string().min(1).max(100),
  avatarUrl: z.url().nullable(),
});
export type User = z.infer<typeof User>;

export const Workspace = z.object({
  id: Id,
  name: z.string().min(1).max(100),
});
export type Workspace = z.infer<typeof Workspace>;

export const ConversationKind = z.enum(['direct', 'group']);
export type ConversationKind = z.infer<typeof ConversationKind>;

export const Conversation = z.object({
  id: Id,
  workspaceId: Id,
  kind: ConversationKind,
  title: z.string().max(100).nullable(),
  memberIds: z.array(Id).min(2),
});
export type Conversation = z.infer<typeof Conversation>;

export const Message = z.object({
  id: Id,
  conversationId: Id,
  senderId: Id,
  /** Generated by the sending device; lets clients replace optimistic messages. */
  clientId: z.uuid(),
  body: z.string().min(1).max(4000),
  createdAt: z.iso.datetime(),
});
export type Message = z.infer<typeof Message>;

export const SendMessageInput = Message.pick({
  conversationId: true,
  clientId: true,
  body: true,
});
export type SendMessageInput = z.infer<typeof SendMessageInput>;
